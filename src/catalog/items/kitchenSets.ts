/* ---------------------------------------------------------------- definitions */

function kitchenSet(sp: KSpec): FurnitureDef {
  const P = planKitchen(sp, sp.size);
  const a = P.anchors.actions ?? {};
  const actions: ActionSpec[] = [];
  if (a.water) actions.push({ kind: 'water', at: a.water });
  if (a.cook) actions.push({ kind: 'cook', at: a.cook });
  if (a.snack) actions.push({ kind: 'snack', at: a.snack });
  return {
    id: sp.id,
    name: sp.name,
    category: 'kitchen',
    group: GROUP,
    tags: sp.tags,
    size: sp.size,
    resize: sp.resize,
    parametric: true,
    colors: sp.colors,
    actions,
    ...(P.anchors.seats?.length ? { seats: P.anchors.seats } : {}),
    build: (ctx) => buildKitchen(sp, ctx.colors, ctx.size ?? sp.size),
    draw2d: (ctx, c, size) => drawKitchen(ctx, sp, c, size ?? sp.size),
  };
}

export const KITCHEN_SETS: FurnitureDef[] = SPECS.map(kitchenSet);
